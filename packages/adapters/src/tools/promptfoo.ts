/**
 * Everything that, if changed, makes a previous result inapplicable.
 *
 * A result is only evidence about the exact experiment that produced it.
 * Change the dataset, the prompt, the candidate, the model configuration, or
 * the evaluator, and the old numbers describe something else. Each identity is
 * carried into the contract individually so that a later reader can see WHICH
 * input moved, not merely that something did.
 */
/**
 * `sha256:` followed by 64 lower-case hex characters.
 *
 * An opaque caller-supplied string is not proof of what ran. Requiring the
 * algorithm and a fixed representation means a fabricated value is rejected
 * rather than recorded as though it were a measurement's identity.
 */
export const DIGEST_PATTERN = /^sha256:[0-9a-f]{64}$/;

export function digestOf(content: string): string {
  return `sha256:${createHash("sha256").update(content, "utf8").digest("hex")}`;
}

/**
 * What each digest covers.
 *
 * Stated explicitly because "a digest" means nothing without the bytes it was
 * taken over. Every one of these is DERIVED by the adapter from the inputs it
 * can actually read, and then compared with the caller's expectation. A
 * caller-supplied value is never recorded as though it were verified.
 *
 * | digest                     | canonical bytes                                        |
 * | -------------------------- | ------------------------------------------------------ |
 * | `config_digest`            | the exact generated bytes passed to `-c`               |
 * | `dataset_hash`             | dataset id, version, and each row WITHOUT its `assert` |
 * | `prompt_hash`              | the ordered list of inline prompt contents             |
 * | `evaluator_hash`           | default assertions plus each row's `assert`, in order  |
 * | `model_configuration_hash` | provider id, config data, and credential NAMES         |
 *
 * These cover DATA the spec holds, not files on disk. An evaluation whose
 * inputs are not fully present cannot have a verifiable identity, so it is
 * refused before it runs rather than recorded with a digest that proves
 * nothing.
 */
export interface EvaluationIdentity {
  readonly workload_ref: string;
  readonly candidate_ref: string;
  readonly dataset_ref: string;
  readonly dataset_version: string;
  /** Expected digests. Each is compared with the value the adapter derives. */
  readonly dataset_hash: string;
  readonly prompt_hash: string;
  readonly evaluator_hash: string;
  readonly model_configuration_hash: string;
  /**
   * The provider this candidate is expected to run against. Checked against
   * what the tool reports; a difference is an attribution failure.
   */
  readonly provider_id?: string | null;
}

/** The identity as recorded, including the values the adapter established. */
export interface VerifiedEvaluationIdentity extends EvaluationIdentity {
  readonly config_digest: string;
  readonly provider_id: string;
  /**
   * Where the evaluation ran, from trusted provider policy. Part of the hashed
   * identity, so evidence measured against one endpoint is never current for
   * another: the same spec run locally, or against a different host, is a
   * different measurement.
   */
  readonly provider_reach: ProviderReach;
  readonly destination_identity: string;
}

export function evaluationIdentityHash(
  identity: EvaluationIdentity | VerifiedEvaluationIdentity,
): string {
  return createHash("sha256")
    .update(stableStringify(identity), "utf8")
    .digest("hex");
}

