/**
 * `ResultFailureReason`, as defined at the pinned promptfoo commit.
 *
 * Source: promptfoo 0.122.0, commit 0170037970dd4732f7542c60ceafa5f4951289de,
 * `src/types/index.ts` lines 375-382:
 *   NONE: 0   -- "The test passed, or we don't know exactly why the test case
 *               failed."
 *   ASSERT: 1 -- "The test case failed because an assertion rejected it."
 *   ERROR: 2  -- "Test case failed due to some other error."
 */
export const PROMPTFOO_FAILURE_REASON = {
  NONE: 0,
  ASSERT: 1,
  ERROR: 2,
} as const;

/**
 * Classify one per-case row the way promptfoo counted it into `stats`.
 *
 * Source, same pinned commit, `src/evaluator.ts`:
 *
 * - `trackRowStats` (line 3387) is the rule the summary was built with:
 *   `success` true is a success; otherwise `failureReason === ERROR` is an
 *   error; otherwise -- ASSERT or NONE -- a failure.
 * - Rows start as `success: false, failureReason: NONE` (lines 1224-1225).
 *   `applyGradingResult` (line 583) sets `success` from the grading pass, and
 *   only on a failed pass sets `failureReason = ASSERT`. Every merge of a later
 *   grading result is `previous && next` (lines 2079, 2089, 2105), so nothing
 *   turns a failed row into a passing one. The only paths that set `success`
 *   true leave `failureReason` at NONE, so a passing row naming ASSERT or ERROR
 *   is not something promptfoo produces: it is refused as contradictory.
 * - `applyGradingError` (line 606), a provider `response.error` (lines
 *   1301-1305), and both timeout results set `success: false,
 *   failureReason: ERROR`.
 *
 * The `error` STRING is deliberately not read. It does not distinguish the
 * categories: `applyGradingResult` sets it on an ordinary assertion failure
 * (line 585), and `applyEmptyResponseOutcome` (line 1334) sets
 * `error = "No output"` (line 1340) while leaving `failureReason` at NONE, which
 * `trackRowStats` counts as a FAILURE. Treating "has an error message" as
 * "is an error" would miscount both.
 *
 * Confirmed against real 0.122.0 output: a passing assertion produced
 * `(true, 0)`, a failing one `(false, 1)` with an error message, an invalid
 * regular expression `(false, 1)` -- an assertion failure, not an error -- and
 * an unreachable local HTTP endpoint `(false, 2)`.
 */
export function classifyCaseRow(row: {
  readonly success?: unknown;
  readonly failureReason?: unknown;
}):
  | { readonly counted: "successes" | "failures" | "errors" }
  | { readonly problem: string } {
  if (typeof row.success !== "boolean") {
    return {
      problem:
        "has no boolean `success`, so whether this case passed cannot be established",
    };
  }
  const reason = row.failureReason;
  if (
    reason !== PROMPTFOO_FAILURE_REASON.NONE &&
    reason !== PROMPTFOO_FAILURE_REASON.ASSERT &&
    reason !== PROMPTFOO_FAILURE_REASON.ERROR
  ) {
    return {
      problem:
        "has no recognised `failureReason` (0, 1 or 2), so how this case was counted cannot be established",
    };
  }
  if (row.success) {
    if (reason !== PROMPTFOO_FAILURE_REASON.NONE) {
      return {
        problem:
          "reports success while naming a failure reason, which promptfoo does not produce; the row contradicts itself",
      };
    }
    return { counted: "successes" };
  }
  return {
    counted: reason === PROMPTFOO_FAILURE_REASON.ERROR ? "errors" : "failures",
  };
}

