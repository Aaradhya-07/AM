function providerIdOf(value: unknown): string | null {
  if (typeof value === "string") {
    return value.length > 0 ? value : null;
  }
  if (value !== null && typeof value === "object" && "id" in value) {
    const id = (value as { id?: unknown }).id;
    return typeof id === "string" && id.length > 0 ? id : null;
  }
  return null;
}

/**
 * Every provider the artifact names, from every documented location.
 *
 * Reading only `results.prompts[].provider` was the defect: an artifact that
 * lists its providers under `results.providers[]` sailed through with no
 * provider established at all, and the evidence recorded `provider_id: null`.
 */
export function collectProviders(
  output: z.infer<typeof PromptfooOutputSchema>,
): {
  readonly providers: readonly string[];
  readonly sources: readonly string[];
} {
  const found = new Map<string, Set<string>>();
  const note = (id: string | null, source: string): void => {
    if (id === null) {
      return;
    }
    const sources = found.get(id) ?? new Set<string>();
    sources.add(source);
    found.set(id, sources);
  };

  for (const prompt of output.results.prompts ?? []) {
    note(
      providerIdOf((prompt as { provider?: unknown }).provider),
      "results.prompts[].provider",
    );
  }
  for (const row of output.results.results ?? []) {
    note(providerIdOf(row.provider), "results.results[].provider");
  }
  for (const entry of output.results.providers ?? []) {
    note(providerIdOf(entry), "results.providers[]");
  }

  const providers = [...found.keys()].sort(compareCodeUnits);
  const sources = [
    ...new Set([...found.values()].flatMap((set) => [...set])),
  ].sort(compareCodeUnits);
  return { providers, sources };
}

