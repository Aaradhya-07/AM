/**
 * Environment that isolates the tool from shared state and from the network
 * features ANVILMARK does not want it using.
 *
 * Sharing and telemetry are off by default because an evaluation carries the
 * user's prompts and dataset rows, and those are default-denied to everything
 * outside the machine.
 */
/** A plain file name: no separators, no traversal, no absolute path. */
export function isSafeArtifactName(name: string): boolean {
  if (name.length === 0 || name === "." || name === "..") {
    return false;
  }
  if (isAbsolute(name)) {
    return false;
  }
  return !/[\\/]/.test(name) && !name.includes("\0");
}

/**
 * Is `candidate` genuinely inside `root` once symlinks are resolved?
 *
 * A directory that resolves outside the declared data directory would put the
 * artifact — and the recursive cleanup that follows — somewhere the caller did
 * not authorise.
 */
export async function isContainedIn(
  root: string,
  candidate: string,
): Promise<boolean> {
  const [realRoot, realCandidate] = await Promise.all([
    realpath(resolve(root)).catch(() => resolve(root)),
    realpath(resolve(candidate)).catch(() => resolve(candidate)),
  ]);
  if (realRoot === realCandidate) {
    return true;
  }
  const rel = relative(realRoot, realCandidate);
  return rel.length > 0 && !rel.startsWith("..") && !isAbsolute(rel);
}

/**
 * The version, taken from a stream that may carry more than the version.
 *
 * A real run found this: promptfoo prints a multi-line update notice on stdout,
 * and taking the whole stream meant the banner was recorded as the producer
 * version of a piece of evidence. Only a bare version token counts, and the
 * LAST one wins, because the notice quotes older versions before the tool
 * prints its own.
 */
export function parseVersion(stdout: string): string | null {
  const versions = stdout
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => /^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$/.test(line));
  return versions.at(-1) ?? null;
}

